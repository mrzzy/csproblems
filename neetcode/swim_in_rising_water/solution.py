from math import inf
from heapq import heappush, heappop
from typing import List


class Solution:
    def swimInWater(self, grid: List[List[int]]) -> int:
        n = len(grid)
        if n != len(grid[0]):
            raise ValueError("Grid should be square")

        # tracks min level seen so far
        min_level = [[inf for _ in range(n)] for _ in range(n)]
        # (max level, position)
        frontier = [(grid[0][0], (0, 0))]
        seen = set()
        while len(frontier) > 0:
            level, (x, y) = heappop(frontier)
            if x == n - 1 and y == n - 1:
                return level
            seen.add((x, y))
            # queue children for exploration
            for x, y in [(x - 1, y), (x + 1, y), (x, y + 1), (x, y - 1)]:
                if 0 <= x < n and 0 <= y < n and (x, y) not in seen:
                    current_level = grid[x][y]
                    next_level = current_level if current_level > level else level

                    # only explore if it actually gives us a smaller distance
                    if next_level < min_level[x][y]:
                        min_level[x][y] = next_level
                        heappush(frontier, (next_level, (x, y)))
        # should not happen
        assert False


