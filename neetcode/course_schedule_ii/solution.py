class Solution:
    def findOrder(self, numCourses: int, prerequisites: list[list[int]]) -> list[int]:
        # compile adjacency list of prerequisites
        self.prerequisite = {a: [] for (a, _) in prerequisites}
        for a, b in prerequisites:
            # course a depends on course
            self.prerequisite[a].append(b)

        full_path, completed = [], set()
        for course in range(numCourses):
            if course in completed:
                # skip if course already completed
                continue

            is_finishable =  self.dfs(course, set(), completed, full_path)
            if not is_finishable:
                # not possible to finish courses
                return []

        return full_path

    def dfs(self, course: int, seen: set[int], completed: set[int], path: list[int]) -> bool:
        """
        Depth first search to find all prerequisites for a course.
        Args:
            course : The course to find prerequisites for.
            seen : A set of courses that have been seen in the current path (to detect cycles).
            completed : A set of courses that have already been completed.
        Returns:
        """
        if course in seen:
            # cyclic dependency, not possible to finish courses
            return False

        prerequisites = self.prerequisite.get(course, [])
        if len(prerequisites) <= 0:
            # course has no prerequisites, finish immiediately
            completed.add(course)
            path.append(course)

        # mark current course as seen
        seen.add(course)

        for dependency in prerequisites:
            if dependency in completed:
                # skip already completed
                continue
            # recursively evalulate task completion for prerequisites first
            is_finishable = self.dfs(dependency, seen, completed, path)
            if not is_finishable:
                # not possible to complete prerequisite and thus the current course
                return False

        seen.remove(course)

        # all prerequisites are complete, so this course can be done now
        completed.add(course)
        path.append(course)

        return True


